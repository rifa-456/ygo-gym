local s,id=GetID()
function s.initial_effect(c)
    Duel.AddCustomActivityCounter(id,ACTIVITY_CHAIN,function() return false end)
    local e=Effect.CreateEffect(c)
    e:SetType(EFFECT_TYPE_ACTIVATE)
    e:SetCode(EVENT_FREE_CHAIN)
    e:SetOperation(s.operation)
    c:RegisterEffect(e)
end
function s.operation(e,tp)
    local ok,message=xpcall(function() s.perform(e,tp) end,function(err) return tostring(err) end)
    assert(ok,message)
end
function s.perform(e,tp)
    local g=Duel.GetMatchingGroup(nil,tp,LOCATION_DECK,0,nil)
    g:KeepAlive()
    local first=g:GetFirst()
    local memory={[tostring(e)]=g}
    local roll=math.random(1,6)
    local selected=Duel.SelectMatchingCard(tp,nil,tp,LOCATION_DECK,0,2,3,nil)
    local next_card=g:GetNext()
    assert(first and next_card and first~=next_card)
    local yes=Duel.SelectYesNo(tp,1)
    assert(g:GetCount()>1 and memory[tostring(e)]==g)
    Duel.SendtoHand(selected,nil,REASON_EFFECT)
    local die=Duel.TossDice(tp,1)
    Duel.Damage(1-tp,die*100+(yes and 50 or 0)+roll+math.random(1,6),REASON_EFFECT)
    g:DeleteGroup()
end
